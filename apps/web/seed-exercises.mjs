// ─── HELPERS ─────────────────────────────────────────────────────────────────

async function upsertExercise(exercise) {
  const { data: existing } = await supabase
    .from("exercises")
    .select("id")
    .eq("name", exercise.name)
    .is("practitioner_id", null)
    .maybeSingle()

  if (existing) {
    console.log(`  ⏭  skip: ${exercise.name}`)
    return existing.id
  }

  const { data, error } = await supabase
    .from("exercises")
    .insert(exercise)
    .select("id")
    .single()

  if (error) {
    console.error(`  ✗  ${exercise.name}:`, error.message)
    return null
  }

  console.log(`  ✓  ${exercise.name}`)
  return data.id
}

async function upsertTemplate(template, exerciseMap) {
  const { data: existing } = await supabase
    .from("program_templates")
    .select("id")
    .eq("name", template.name)
    .is("practitioner_id", null)
    .maybeSingle()

  let templateId

  if (existing) {
    console.log(`  ⏭  skip template: ${template.name}`)
    templateId = existing.id
  } else {
    const { data, error } = await supabase
      .from("program_templates")
      .insert({
        name: template.name,
        description: template.description,
        body_part: template.body_part,
        duration_weeks: template.duration_weeks,
        is_public: true,
        practitioner_id: null,
      })
      .select("id")
      .single()

    if (error) {
      console.error(`  ✗  template ${template.name}:`, error.message)
      return
    }

    templateId = data.id
    console.log(`  ✓  template: ${template.name}`)
  }

  // insert items only if template was just created
  if (!existing) {
    const items = []
    for (let i = 0; i < template.exercises.length; i++) {
      const ex = template.exercises[i]
      const exerciseId = exerciseMap[ex.name]
      if (!exerciseId) {
        console.warn(`  ⚠  exercise not found for template item: ${ex.name}`)
        continue
      }
      items.push({
        template_id: templateId,
        exercise_id: exerciseId,
        order: i + 1,
        sets: ex.sets ?? null,
        reps: ex.reps ?? null,
        duration_seconds: ex.duration_seconds ?? null,
        rest_seconds: ex.rest ?? null,
        notes: ex.notes ?? null,
      })
    }

    if (items.length > 0) {
      const { error: itemsError } = await supabase
        .from("program_template_items")
        .insert(items)

      if (itemsError) {
        console.error(`  ✗  template items for ${template.name}:`, itemsError.message)
      } else {
        console.log(`     → ${items.length} ćwiczeń dodano do szablonu`)
      }
    }
  }
}

// ─── MAIN ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log("=== Seeding exercises ===")
  const exerciseMap = {}

  for (const exercise of exercises) {
    const id = await upsertExercise(exercise)
    if (id) exerciseMap[exercise.name] = id
  }

  console.log(`\nZapisano ${Object.keys(exerciseMap).length} / ${exercises.length} ćwiczeń\n`)

  console.log("=== Seeding program templates ===")
  for (const template of programTemplates) {
    await upsertTemplate(template, exerciseMap)
  }

  console.log("\nGotowe!")
}

